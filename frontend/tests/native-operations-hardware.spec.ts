import {test,expect} from '@playwright/test'
test('installed native page identifies the SD and opens confirmation without formatting',async({page},info)=>{
 test.skip(process.env.NCC_NATIVE_OPERATIONS_HARDWARE!=='1','Explicit installed-device read-only verification')
 test.setTimeout(90000)
 const errors:string[]=[],writes:string[]=[]
 page.on('pageerror',error=>errors.push(error.message))
 page.on('request',request=>{if(request.method()!=='GET'&&request.url().includes('/native-operations/'))writes.push(new URL(request.url()).pathname)})
 await page.goto('/#native')
 const format=page.getByRole('button',{name:'SDカードをフォーマット',exact:true})
 await expect(format).toBeEnabled({timeout:45000})
 const storage=await (await page.request.get('/api/v1/device/native-operations/state/storage')).json()
 expect(storage.values.inserted).toBe(1);expect(storage.values.formatStatus).toBe(2)
 await format.click()
 const dialog=page.getByRole('dialog',{name:'SDカードをフォーマット'})
 await expect(dialog).toBeVisible();await expect(dialog).toContainText('すべてのデータを消去')
 await expect(dialog.getByRole('button',{name:'SDカードの全データを消去してフォーマット'})).toBeDisabled()
 await dialog.screenshot({path:info.outputPath('sd-format-confirmation.private.png')})
 await dialog.getByRole('button',{name:'キャンセル',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 expect(writes).toEqual(['/api/v1/device/native-operations/sd-format/prepare'])
 await page.goto('/#system/recorder')
 for(const label of ['前方カメラの録画品質','駐車監視'])await expect(page.getByRole('combobox',{name:label,exact:true})).toBeEnabled()
 await expect(page.getByRole('heading',{name:'H.264詳細録画設定',exact:true})).toBeVisible()
 await page.goto('/#native')
 await expect(page.getByRole('combobox',{name:'車種',exact:true})).toBeEnabled()
 await page.getByRole('button',{name:/操作・診断/}).click()
 for(const pair of [{category:'調整・診断',button:'GNSSの受信状態を取得',region:'GNSS・センサーの操作',value:'受信衛星数'},{category:'調整・診断',button:'リアウインドウの学習状態',region:'取付の調整の操作',value:'学習状態'},{category:'保守・セットアップ',button:'保守モードを取得',region:'保守・シリアルの操作',value:'保守モード'},{category:'接続・アカウント',button:'純正Wi-Fiの状態を取得',region:'純正Wi-Fi接続の操作',value:'本体の応答を確認しました。'},{category:'接続・アカウント',button:'純正APの状態を取得',region:'純正ローカルAPの操作',value:'本体の応答を確認しました。'}]){
  await page.getByRole('button',{name:new RegExp(pair.category)}).click()
  await page.getByRole('button',{name:pair.button,exact:true}).click()
  await expect(page.getByRole('region',{name:pair.region}).getByRole('status')).toContainText(pair.value,{timeout:15000})
 }
 await page.getByRole('button',{name:/調整・診断/}).click()
 await expect(page.getByRole('button',{name:'センサートリップを取得',exact:true})).toBeDisabled()
 await page.getByRole('button',{name:/保守・セットアップ/}).click()
 await expect(page.getByRole('button',{name:'純正ファームウェアを確認',exact:true})).toBeDisabled()
 expect(writes).toEqual(['/api/v1/device/native-operations/sd-format/prepare'])
 const grid=page.locator('.native-action-grid')
 expect(await grid.evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBeGreaterThan(1)
 await grid.screenshot({path:info.outputPath('operation-grid-desktop.private.png')})
 await page.setViewportSize({width:390,height:844})
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.getByRole('heading',{name:'操作・診断',exact:true}).scrollIntoViewIfNeeded()
 await page.screenshot({path:info.outputPath('native-operations-mobile.private.png')})
 expect(errors).toEqual([])
})

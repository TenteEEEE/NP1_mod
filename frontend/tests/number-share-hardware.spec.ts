import {test,expect} from '@playwright/test'

test.skip(process.env.NCC_PLATE_HARDWARE!=='1','Explicit read-only device UI verification')

test('installed NumberShare tab hides the saved key until explicitly revealed',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 await page.setViewportSize({width:390,height:900})
 await page.goto('/#plates')
 await page.getByRole('tab',{name:'共有',exact:true}).click()
 await expect(page.getByRole('heading',{name:'NumberShare API',exact:true})).toBeVisible()
 await expect(page.getByLabel('APIエンドポイント',{exact:true})).toBeVisible()
 await expect(page.getByLabel('認証キー',{exact:true})).toHaveAttribute('type','password')
 await expect(page.getByLabel('認証キー',{exact:true})).not.toHaveValue('')
 await page.getByLabel('認証キーを表示する',{exact:true}).check()
 await expect(page.getByLabel('認証キー',{exact:true})).toHaveAttribute('type','text')
 await expect(page.getByRole('heading',{name:'期間を指定してアップロード',exact:true})).toBeVisible()
 await expect(page.locator('.share-upload').getByLabel('開始日')).toBeVisible()
 await expect(page.locator('.share-upload').getByLabel('終了日')).toBeVisible()
 await expect(page.getByRole('button',{name:'この期間をアップロード',exact:true})).toBeEnabled()
 await expect(page.getByRole('heading',{name:'APIの全検知履歴',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'APIから全件受信',exact:true})).toBeEnabled()
 const response=await page.request.get('/api/v1/plate/share/status')
 expect(response.status()).toBe(200)
 const body=await response.json()
 expect(body.config).toMatchObject({enabled:false,keyConfigured:true})
 expect(body.config.apiKey).toBeTruthy()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 expect(errors).toEqual([])
})
